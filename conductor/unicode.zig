// Characters as a terminal shows them: decoded from UTF-8, and the columns
// each takes. Shared with the client, which follows a remote prompt's row.

const std = @import("std");

/// The character `text` starts with: its code point and length in bytes;
/// null for a byte that doesn't start valid UTF-8.
pub fn decode(text: []const u8) ?struct { cp: u21, len: u3 } {
    const len = std.unicode.utf8ByteSequenceLength(text[0]) catch return null;
    if (len > text.len) return null;
    const cp: u21 = switch (len) {
        1 => text[0],
        2 => std.unicode.utf8Decode2(text[0..2].*) catch return null,
        3 => std.unicode.utf8Decode3(text[0..3].*) catch return null,
        4 => std.unicode.utf8Decode4(text[0..4].*) catch return null,
        else => unreachable,
    };
    return .{ .cp = cp, .len = len };
}

/// The columns a terminal gives `cp`: none for a control or a character
/// that joins the one before (a combining mark, a joiner, a variation
/// selector), two for East Asian wide and fullwidth characters and emoji.
pub fn codepointWidth(cp: u21) u2 {
    if (cp < 0x20 or (cp >= 0x7f and cp < 0xa0)) return 0;
    if (cp < 0x300) return 1;
    if (inRanges(&zero_width, cp)) return 0;
    return if (inRanges(&wide, cp)) 2 else 1;
}

fn inRanges(ranges: []const [2]u21, cp: u21) bool {
    for (ranges) |range| {
        if (cp < range[0]) return false;
        if (cp <= range[1]) return true;
    }
    return false;
}

